function replaceTemplateVars(text: string, vars: Record<string, string>): string {
  return text.replace(/\{\{(\w+)\}\}/g, (match, key) => vars[key] || match);
}

export function getTranslation(
  lang: string,
  section: keyof typeof emailTranslations.pt,
  key: string,
  vars?: Record<string, string>
): string {
  const defaultLang = 'pt';
  const translations = emailTranslations[lang as keyof typeof emailTranslations] || emailTranslations[defaultLang];
  const sectionTranslations = translations[section] as Record<string, string>;
  let text = sectionTranslations[key] || (emailTranslations[defaultLang][section] as Record<string, string>)[key] || key;

  if (vars) {
    text = replaceTemplateVars(text, vars);
  }

  return text;
}

export function detectLanguageFromEmail(email: string | null | undefined): string {
  if (!email) return 'pt';
  const domain = email.split('@')[1]?.toLowerCase() || '';

  if (domain.endsWith('.pt')) return 'pt';
  if (domain.endsWith('.es')) return 'es';
  if (domain.endsWith('.it')) return 'it';
  if (domain.endsWith('.fr')) return 'fr';

  return 'pt';
}
